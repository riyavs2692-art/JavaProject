package conditionalstatements;

public class Switchpgm {

	public static void main(String[] args) {
	
		int n=2;
		
		switch(n)
		{
		case 1: System.out.println("Sunday");
		break; //to terminate the execution of switch block after the condition satisfies
		case 2 :System.out.println("Monday");
		break ;
		case 3:System.out.println("Tueday");
		break; 
		case 4 :System.out.println("Wedensday");
		break;
		case 5 :System.out.println("Thurday");
		break;
		case 6 :System.out.println("Friday");
		break;
		case 7 :System.out.println("saturday");
		break;
		
		default: System.out.println("Invalid option");
		}
		
		
		
		}
	}
	






