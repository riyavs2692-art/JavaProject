package javapackage;

public class Datatypepgm {

	public static void main(String[] args) {
		
    byte byteNumber=10;
    System.out.println("The value of byteNumber = "+byteNumber);
    
    short shortNumber=20;
    System.out.println("The value of shortNumber = "+shortNumber);
    
    int intNumber=15;
    System.out.println("The value of integerNumber = "+intNumber);
    
    long longNumber=104489655225L;
    System.out.println("The value of longNumber = "+longNumber);
    
    float floatNumber=2.01F;
    System.out.println("The value of floatNumber= " +floatNumber);
    
    double doubleNumber=3.58495;
    System.out.println("The value of doubleNumber = "+doubleNumber);
    
    boolean result = 5>3;
    System.out.println("The value of result = " +result);
    
    char charValue = 'R';//char value should be enclosed within single quotes
    System.out.println("The value of charValue = "+charValue);
    
    char symbol = '%';   
    System.out.println("The value of symbol = "+symbol);
    
    String name = "Jacob";
    System.out.println("The value of StringName = "+name);
    
    
    
    
	}

}
